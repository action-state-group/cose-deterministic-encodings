#!/usr/bin/env bash
# Local check run before every push: the commands the pull_request and main CI jobs run,
# whatever paths a change touches. Needs go, uv and kramdown-rfc (gem install kramdown-rfc) on PATH.
# Not run here: dco (commit sign-off) and build.yml's idnits step (non-gating in CI).
set -euo pipefail
cd "$(dirname "$0")/.."
command -v kramdown-rfc >/dev/null || { echo "kramdown-rfc not on PATH: gem install kramdown-rfc" >&2; exit 1; }
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
export PYTHONDONTWRITEBYTECODE=1
py() { uv run --isolated --no-project --python 3.12 --with xml2rfc "$@"; }

# impl.yml: python
py python vectors/generate.py --check
py python -m unittest discover -s lib/python -v
# impl.yml: go
(cd lib/go && test -z "$(gofmt -l .)" && go vet ./... && go test ./...)
# build.yml: rebuild the draft and compare with the committed .xml and .txt
DRAFT=$(grep '^DRAFT[[:space:]]*=' Makefile | sed 's/^DRAFT[[:space:]]*=[[:space:]]*//')
kramdown-rfc "$DRAFT.md" > "$work/.draft.v2.xml"
py xml2rfc --quiet --v2v3 "$work/.draft.v2.xml" -o "$work/$DRAFT.v3pi.xml"
sed '/^[[:space:]]*<?line [0-9]*?>[[:space:]]*$/d' "$work/$DRAFT.v3pi.xml" > "$work/$DRAFT.xml"
if grep -n '<?line' "$work/$DRAFT.xml"; then echo "a <?line?> PI is left in $DRAFT.xml"; exit 1; fi
py xml2rfc --quiet --text --v3 "$work/$DRAFT.xml" -o "$work/$DRAFT.txt"
strip_xml() {
  grep -v -e 'generated by.*kramdown-rfc' -e '^ *<!-- xml2rfc v2v3 conversion [0-9][0-9.]* -->$' |
    sed 's/<date year="[^"]*" month="[^"]*" day="[^"]*"\/>/<date\/>/g'
}
strip_txt() {
  sed \
    -e 's/^Expires: [0-9][0-9]* [A-Za-z][A-Za-z]* [0-9][0-9][0-9][0-9]/Expires: DATE_NORM/' \
    -e 's/expire on [0-9][0-9]* [A-Za-z][A-Za-z]* [0-9][0-9][0-9][0-9]/expire on DATE_NORM/' \
    -e 's/Expires [0-9][0-9]* [A-Za-z][A-Za-z]* [0-9][0-9][0-9][0-9]  *\[Page/Expires DATE_NORM [Page/' \
    -e '/^ *[0-9][0-9]* [A-Za-z][A-Za-z]* [0-9][0-9][0-9][0-9] *$/s/.*/DATE_NORM/' \
    -e '/DATE_NORM/s/  */ /g'
}
diff <(strip_xml < "$DRAFT.xml") <(strip_xml < "$work/$DRAFT.xml") || { echo "STALE: $DRAFT.xml"; exit 1; }
diff <(strip_txt < "$DRAFT.txt") <(strip_txt < "$work/$DRAFT.txt") || { echo "STALE: $DRAFT.txt"; exit 1; }
grep -q 'version="3"' "$work/$DRAFT.xml"
echo "check.sh: all checks passed"
